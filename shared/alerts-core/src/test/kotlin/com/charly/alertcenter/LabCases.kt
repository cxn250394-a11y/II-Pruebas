package com.charly.alertcenter

object LabCases {
    private fun a(id: Long = 1, source: String = "org.telegram.messenger", profile: Int = 0,
                  title: String = "Canal", body: String = "Hola", received: Long = 1000,
                  read: Boolean = false) = LabAlert(id, source, profile, title, body, received, received, read = read)
    private fun sport(text: String, kind: SportMention?) = LabEngine.sportMention("Azul vs Verde", text, AlertCategory.SPORTS) == kind
    val all: List<Pair<String, () -> Boolean>> = listOf(
        "chronological newest first" to { LabEngine.sorted(listOf(a(1, received=100), a(2, received=300), a(3, received=200))).map { it.id } == listOf(2L,3L,1L) },
        "stable order for identical reception time" to { LabEngine.sorted(listOf(a(1), a(2))).first().id == 2L },
        "groups keep most recent at front" to { LabEngine.groups(listOf(a(1,received=1),a(2,received=2))).single().latest.id == 2L },
        "unread is local state" to { LabEngine.groups(listOf(a(1),a(2,read=true))).single().unread == 1 },
        "clients do not merge" to { LabEngine.groups(listOf(a(),a(2,source="app.nicegram"))).size == 2 },
        "Android profiles do not merge" to { LabEngine.groups(listOf(a(),a(2,profile=999))).size == 2 },
        "different titles remain separate" to { LabEngine.groups(listOf(a(),a(2,title="Otro"))).size == 2 },
        "exact titles not normalized into false identity" to { a(title="Canál").groupKey != a(title="Canal").groupKey },
        "title grouping is not account identity" to { a(id=1).groupKey == a(id=2).groupKey },
        "empty title safe" to { LabEngine.groups(listOf(a(title=""))).single().latest.title.isEmpty() },
        "search without accents" to { LabEngine.matches(a(body="Córner a favor"), "corner") },
        "search source" to { LabEngine.matches(a(), "telegram") },
        "search does not invent matches" to { !LabEngine.matches(a(), "tarjeta") },
        "empty search includes all" to { LabEngine.matches(a(), " ") },
        "search includes record beyond first 250" to { (1..600).map { a(it.toLong(),body="aviso $it") }.filter { LabEngine.matches(it,"aviso 510") }.size == 1 },
        "different timestamps preserve repeated message" to { LabEngine.eventKey("a",0,"k","t","hola",1) != LabEngine.eventKey("a",0,"k","t","hola",2) },
        "same timestamp different occurrences preserved" to { LabEngine.eventKey("a",0,"k","t","hola",1,0) != LabEngine.eventKey("a",0,"k","t","hola",1,1) },
        "identical event key deterministic" to { LabEngine.eventKey("a",0,"k","t","hola",1) == LabEngine.eventKey("a",0,"k","t","hola",1) },
        "different clients distinct event IDs" to { LabEngine.eventKey("a",0,"k","t","hola",1) != LabEngine.eventKey("b",0,"k","t","hola",1) },
        "different profiles distinct event IDs" to { LabEngine.eventKey("a",0,"k","t","hola",1) != LabEngine.eventKey("a",999,"k","t","hola",1) },
        "length prefix avoids ambiguous separators" to { LabEngine.digest("a", "b:c") != LabEngine.digest("a:b", "c") },
        "raw content case not deduped away" to { LabEngine.eventKey("a",0,"k","t","Hola",1) != LabEngine.eventKey("a",0,"k","t","hola",1) },
        "folder name accepted" to { LabEngine.validFolder("Mis canales") },
        "blank folder rejected" to { !LabEngine.validFolder(" ") },
        "long folder rejected" to { !LabEngine.validFolder("x".repeat(37)) },
        "control chars rejected" to { !LabEngine.validFolder("a\nb") },
        "goal mention" to { sport("¡GOL! Minuto 32", SportMention.GOAL) },
        "long goal mention" to { sport("GOOOOL 2-1", SportMention.GOAL) },
        "english goal" to { sport("GOAL 74'", SportMention.GOAL) },
        "corner mention" to { sport("Córner 55'", SportMention.CORNER) },
        "corner phrase" to { sport("Saque de esquina 55'", SportMention.CORNER) },
        "red card" to { sport("Tarjeta roja 61'", SportMention.RED) },
        "yellow card" to { sport("Yellow card 28'", SportMention.YELLOW) },
        "penalty" to { sport("Penalti 90'", SportMention.PENALTY) },
        "VAR does not confirm goal" to { sport("Gol en revisión VAR", SportMention.VAR) },
        "cancelled goal overrides VAR" to { sport("Gol anulado por VAR", SportMention.DISALLOWED) },
        "english correction" to { sport("Goal ruled out", SportMention.DISALLOWED) },
        "no goal is correction not score" to { sport("No goal", SportMention.DISALLOWED) },
        "multiple mentions not counted" to { sport("Gol y tarjeta roja", SportMention.MULTIPLE) },
        "score alone insufficient" to { sport("Marcador 2-1", null) },
        "golpe is not goal" to { sport("Golpe fuerte", null) },
        "ad rejected" to { sport("Gol con cuota mejorada", null) },
        "prediction rejected" to { sport("Pick: córner antes del minuto 10", null) },
        "question rejected" to { sport("¿Habrá gol?", null) },
        "negation rejected" to { sport("No hubo córner", null) },
        "no goals not positive" to { sport("Sin goles al descanso", null) },
        "future event rejected" to { sport("Habrá penal en el segundo tiempo", null) },
        "telegram tip not sports event" to { LabEngine.sportMention("Canal", "Gol de Azul", AlertCategory.TELEGRAM) == null },
        "other source not sports event" to { LabEngine.sportMention("Canal", "Gol de Azul", AlertCategory.OTHER) == null },
        "demo has no positive DB IDs" to { LabEngine.demo(1_000_000).all { it.id < 0 } },
        "demo includes explicit correction" to { LabEngine.demo(1_000_000).any { it.body.contains("anulado") } },
        "demo stable for same clock" to { LabEngine.demo(1_000_000) == LabEngine.demo(1_000_000) },
        "demo limited data size" to { LabEngine.demo(1_000_000).size == 7 },
        "OTP redaction remains enabled" to { AlertRules.isLikelySensitive("Verification code 123456", "") },
        "keyword word boundaries" to { !AlertRules.hasPriorityWord("Golpe", "", "gol") }
    )
}
